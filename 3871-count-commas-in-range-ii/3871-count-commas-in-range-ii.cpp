class Solution {
public:
    long long countCommas(long long n) {
        if (n < 1000)
            return 0;
        else if (n >= 1000 && n < 1000000) {
            return (n - 1000) + 1;
        }
        
         else if (n >= 1000000 && n < 1000000000) {
            return (n - 1000000) * 2 + 2 +999000;
        }

        else if (n >= 1000000000 && n <1000000000000) {
            return (n - 1000000000) * 3 + 3 +999000000*2+999000;
        }

        else if (n >= 1000000000000 && n < 1000000000000000) {
            return (n - 1000000000000) * 4 + 4 + 999000000000*3+999000000*2+999000;
        }
        else {
            return 999000000000000*4+5+999000000000*3+999000000*2+999000;
        }
    }
};